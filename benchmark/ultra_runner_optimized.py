import os
import subprocess
import time
import statistics
import sys
import shutil
import re

class UltraRunner:
    def __init__(self):
        self.suite_dir = "benchmark/ultra_suite"
        self.ocean_src_dir = "examples"
        self.results = {}
        # Correct classpath using the actual JAR and build folders
        self.ocean_cp = "build/libs/Ocean-all.jar;build/classes/java/main;build/resources/main;." 
        
    def run_cmd(self, cmd, cwd=None):
        try:
            start = time.time()
            # Specify utf-8 encoding
            result = subprocess.run(cmd, shell=True, capture_output=True, text=True, cwd=cwd, timeout=600, encoding='utf-8', errors='replace')
            end = time.time()
            return (end - start) * 1000, result.stdout, result.stderr
        except Exception as e:
            return -1, "", str(e)

    def parse_internal_time(self, output):
        # Look for "Time: 123 ms" or "Time: 123.4 ms" or "Time: 123ms"
        match = re.search(r"Time[:\s]+(\d+[\.]?\d*)\s*ms", output, re.IGNORECASE)
        if match:
            return float(match.group(1))
        return None

    def compile_all(self):
        print("--- Compiling All Benchmarks ---", flush=True)
        # 1. C/C++, Java, C#
        for cat in os.listdir(self.suite_dir):
            cat_path = os.path.join(self.suite_dir, cat)
            if not os.path.isdir(cat_path): continue
            
            for file in os.listdir(cat_path):
                if file.endswith(".c"):
                    print(f" Compiling C: {file}", flush=True)
                    self.run_cmd(f"gcc -O3 {file} -o {file[:-2]}.exe -lm", cwd=cat_path)
                elif file.endswith(".cpp"):
                    print(f" Compiling CPP: {file}", flush=True)
                    self.run_cmd(f"g++ -O3 {file} -o {file[:-4]}_cpp.exe", cwd=cat_path)
                elif file.endswith(".java"):
                    print(f" Compiling Java: {file}", flush=True)
                    self.run_cmd(f"javac {file}", cwd=cat_path)
                elif file.endswith(".cs") and "Program" not in file:
                    print(f" Preparing C# for {file}", flush=True)
                    # Create project if not exists
                    if not os.path.exists(os.path.join(cat_path, f"{cat}.csproj")):
                        self.run_cmd(f"dotnet new console --force", cwd=cat_path)
                    
                    # Remove the default Program.cs generated by dotnet new, if it exists
                    default_prog = os.path.join(cat_path, "Program.cs")
                    if os.path.exists(default_prog):
                        os.remove(default_prog)
                        
                    self.run_cmd(f"dotnet build -c Release", cwd=cat_path)

        # 2. Ocean
        print(" Compiling Ocean files...", flush=True)
        for file in os.listdir(self.ocean_src_dir):
            if file.endswith("Bench.ocean") or file == "ParallelSum.ocean":
                print(f"   Compiling: {file}", flush=True)
                # Ensure ocean.bat is in Cwd
                self.run_cmd(f"cmd /c ocean.bat {file[:-6]}", cwd=".")

    def benchmark(self, lang, cmd, cwd, iterations=5):
        print(f"  {lang:<10} ", end="", flush=True)
        # Warm-up (2 times)
        for _ in range(2):
            self.run_cmd(cmd, cwd=cwd)
        
        times = []
        for _ in range(iterations):
            val_t, out, err = self.run_cmd(cmd, cwd=cwd)
            if val_t < 0 or "Exception" in err or "Error" in err or "Could not find or load main class" in err: 
                print("F", end="", flush=True)
                continue
            
            internal = self.parse_internal_time(out)
            if internal is not None:
                times.append(internal)
            else:
                # Fallback to wall if internal printer not found
                times.append(val_t)
            print(".", end="", flush=True)
        
        if not times:
            print(" NO DATA")
            return None
            
        avg = statistics.mean(times)
        print(f" {avg:.1f} ms")
        return avg

    def get_run_command(self, cat_dir, lang, short_name):
        cat_path = os.path.join(self.suite_dir, cat_dir)
        if lang == "C":
            exes = [f for f in os.listdir(cat_path) if f.endswith(".exe") and "cpp" not in f.lower()]
            if not exes: return None, None
            return f".\\{exes[0]}", cat_path
        elif lang == "CPP":
            exes = [f for f in os.listdir(cat_path) if f.endswith(".exe") and "cpp" in f.lower()]
            if not exes: return None, None
            return f".\\{exes[0]}", cat_path
        elif lang == "Java":
            # Find the .java file in cat_path
            for file in os.listdir(cat_path):
                if file.endswith(".java"):
                    return f"java {file[:-5]}", cat_path
            return f"java {short_name}", cat_path
        elif lang == "CSHARP":
            return f"dotnet run -c Release --no-build", cat_path
        elif lang == "Ocean":
            # Ocean class name might be different from file name
            # Ocean class names usually match the short_name
            className = short_name
            if short_name == "Primes": className = "Primes"
            # Overrides if any (currently they seem to match short_name)
            
            return f"java -cp \"{self.ocean_cp}\" ocean.compiler.generated.{className}", "."
        return None, None

    def execute_all(self):
        langs = ["C", "CPP", "Java", "CSHARP", "Ocean"]
        categories = [
            ("cpu_primes", "Primes"),
            ("memory_stress", "ArrayBench"),
            ("oop_gc", "NodesBench"),
            ("call_overhead", "CallsBench"),
            ("math_fp", "MathBench"),
            ("ds_maps", "HashMapBench"),
            ("thread_parallel", "ParallelSum"),
            ("mixed_world", "JsonBench")
        ]

        for cat_dir, short_name in categories:
            print(f"\n[Category: {cat_dir}]")
            self.results[cat_dir] = {}
            for lang in langs:
                sname = short_name
                if cat_dir == "cpu_primes" and lang in ["C", "CPP"]: sname = "primes"
                if cat_dir == "memory_stress" and lang in ["C", "CPP"]: sname = "array_bench"
                if cat_dir == "oop_gc" and lang in ["C", "CPP"]: sname = "nodes"
                if cat_dir == "call_overhead" and lang in ["C", "CPP"]: sname = "calls"
                if cat_dir == "math_fp" and lang in ["C", "CPP"]: sname = "math_bench"
                if cat_dir == "ds_maps" and lang in ["C", "CPP"]: sname = "hash_map"
                if cat_dir == "thread_parallel" and lang in ["C", "CPP"]: sname = "parallel_sum"
                if cat_dir == "io_bound" and lang in ["C", "CPP"]: sname = "io_bench"
                if cat_dir == "mixed_world" and lang in ["C", "CPP"]: sname = "json_bench"
                
                cmd, cwd = self.get_run_command(cat_dir, lang, sname)
                if cmd:
                    self.results[cat_dir][lang] = self.benchmark(lang, cmd, cwd)

    def print_report(self):
        header = "| Category | C (ms) | C++ (ms) | Java (ms) | C# (ms) | Ocean (ms) |"
        sep = "| :--- | :---: | :---: | :---: | :---: | :---: |"
        print("\n\nFINAL REPORT\n")
        print(header)
        print(sep)
        for cat, data in self.results.items():
            row = f"| {cat} |"
            for lang in ["C", "CPP", "Java", "CSHARP", "Ocean"]:
                val = data.get(lang)
                row += f" {val:.1f} |" if val is not None else " N/A |"
            print(row)

if __name__ == "__main__":
    runner = UltraRunner()
    runner.compile_all()
    runner.execute_all()
    runner.print_report()
